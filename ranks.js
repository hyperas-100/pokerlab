/* PokerLab ranges + Monte Carlo equity.
   ORDER is the 169 starting hands sorted by playability (equity vs a random hand, adjusted for suitedness and
   connectivity; generated by test/genranks.js). Percentiles are "top X pct of all hands" using combo counts. */
(function () {
  const PK = (globalThis.PK = globalThis.PK || {});
  const E = PK.Engine || require('./engine.js');
  const { eval7 } = E;
  const RS = '23456789TJQKA';
  const ORDER = ["AA","KK","QQ","JJ","TT","AKs","99","AQs","AJs","88","KQs","ATs","77","AKo","KTs","KJs","A9s","AQo","A8s","A7s","QJs","AJo","66","QTs","A6s","A5s","ATo","K9s","JTs","A4s","KQo","A3s","KJo","Q9s","A2s","55","KTo","K8s","J9s","K7s","K6s","QJo","T9s","QTo","Q8s","K4s","K5s","A9o","J8s","Q7s","A8o","44","T8s","K2s","K3s","A7o","Q6s","JTo","Q5s","98s","A6o","A5o","Q9o","K9o","T7s","J7s","A4o","Q4s","J9o","33","J6s","Q3s","K8o","A3o","Q2s","97s","T9o","K7o","A2o","J5s","87s","J4s","Q8o","J8o","T6s","K6o","96s","J3s","K5o","T8o","22","86s","Q7o","K4o","Q6o","J2s","76s","T5s","98o","J7o","K3o","T4s","Q5o","T3s","95s","65s","T7o","75s","97o","K2o","T2s","85s","Q4o","T6o","J6o","94s","87o","J5o","Q3o","93s","Q2o","84s","96o","J4o","92s","T5o","J3o","T4o","86o","74s","83s","J2o","64s","76o","54s","95o","82s","73s","T3o","85o","63s","53s","T2o","75o","43s","72s","93o","94o","65o","62s","84o","52s","92o","64o","74o","42s","83o","32s","54o","73o","82o","63o","53o","43o","52o","72o","62o","42o","32o"];
  const combosOf = (k) => (k.length === 2 ? 6 : k[2] === 's' ? 4 : 12);
  const MID = {}; { let cum = 0; for (const k of ORDER) { const c = combosOf(k); MID[k] = (cum + c / 2) / 1326; cum += c; } }
  function keyOf(c1, c2) {
    let a = c1 >> 2, b = c2 >> 2; const suited = (c1 & 3) === (c2 & 3);
    if (a < b) { const t = a; a = b; b = t; }
    return a === b ? RS[a] + RS[b] : RS[a] + RS[b] + (suited ? 's' : 'o');
  }
  const pct = (hole) => MID[keyOf(hole[0], hole[1])];
  /* all 1326 combos with their percentile, sorted best to worst */
  const ALL = [];
  for (let a = 0; a < 52; a++) for (let b = a + 1; b < 52; b++) ALL.push({ c: [a, b], p: MID[keyOf(a, b)] });
  ALL.sort((x, y) => x.p - y.p);
  /* combos with lo < pct <= hi that do not clash with dead cards (array of card ints) */
  function pool(lo, hi, dead) {
    const dd = new Uint8Array(52); for (const d of dead || []) dd[d] = 1;
    const out = [];
    for (const x of ALL) { if (x.p > hi) break; if (x.p > lo && !dd[x.c[0]] && !dd[x.c[1]]) out.push(x.c); }
    return out;
  }
  const BASE_DECK = Array.from({ length: 52 }, (_, i) => i);
  /* Equity of hero vs opponents. opps: array of (number = random hand) or array of combos (a range pool). */
  function equity(hero, board, opps, sims, rnd) {
    rnd = rnd || Math.random;
    const used = new Uint8Array(52);
    const base = hero.concat(board);
    const rem = BASE_DECK.filter((c) => base.indexOf(c) < 0);
    const need = 5 - board.length, nO = opps.length;
    let win = 0, tie = 0, done = 0;
    const full = new Array(7), ofull = new Array(7);
    for (let s = 0; s < sims; s++) {
      used.fill(0); for (const c of base) used[c] = 1;
      let ok = true; const oh = [];
      for (let i = 0; i < nO && ok; i++) {
        const o = opps[i];
        if (typeof o === 'number') {
          let a, b; do { a = rem[(rnd() * rem.length) | 0]; } while (used[a]); used[a] = 1; do { b = rem[(rnd() * rem.length) | 0]; } while (used[b]); used[b] = 1; oh.push([a, b]);
        } else {
          let tries = 0, pick = null;
          while (tries++ < 25) { const x = o[(rnd() * o.length) | 0]; if (!used[x[0]] && !used[x[1]]) { pick = x; break; } }
          if (!pick) { ok = false; break; }
          used[pick[0]] = used[pick[1]] = 1; oh.push(pick);
        }
      }
      if (!ok) continue;
      const bd = board.slice();
      for (let i = 0; i < need; i++) { let c; do { c = rem[(rnd() * rem.length) | 0]; } while (used[c]); used[c] = 1; bd.push(c); }
      full[0] = hero[0]; full[1] = hero[1]; for (let j = 0; j < 5; j++) full[2 + j] = bd[j];
      const hs = eval7(full);
      let best = -1, nBest = 0;
      for (let i = 0; i < nO; i++) {
        ofull[0] = oh[i][0]; ofull[1] = oh[i][1]; for (let j = 0; j < 5; j++) ofull[2 + j] = bd[j];
        const sc = eval7(ofull); if (sc > best) { best = sc; nBest = 1; } else if (sc === best) nBest++;
      }
      if (hs > best) win++; else if (hs === best) tie += 1 / (nBest + 1);
      done++;
    }
    return done ? (win + tie) / done : 0.5;
  }
  /* flush / straight draws on flop or turn. returns {fd, oesd, gut} */
  function draws(hole, board) {
    const cards = hole.concat(board), res = { fd: false, oesd: false, gut: false };
    const sc = [0, 0, 0, 0], sh = [0, 0, 0, 0];
    for (const c of cards) sc[c & 3]++;
    for (const c of hole) sh[c & 3]++;
    for (let s = 0; s < 4; s++) if (sc[s] === 4 && sh[s] >= 1) res.fd = true;
    let mask = 0; for (const c of cards) mask |= 1 << (c >> 2);
    const has = (m, r) => (r === -1 ? (m >> 12) & 1 : (m >> r) & 1);
    const straight = (m) => { for (let lo = -1; lo <= 8; lo++) { let all = true; for (let k = 0; k < 5; k++) if (!has(m, lo + k)) { all = false; break; } if (all) return true; } return false; };
    if (!straight(mask)) {
      let outs = 0;
      for (let add = 0; add < 13; add++) if (!((mask >> add) & 1) && straight(mask | (1 << add))) outs++;
      if (outs >= 2) res.oesd = true; else if (outs === 1) res.gut = true;
    }
    return res;
  }
  PK.Range = { ORDER, MID, keyOf, pct, ALL, pool, equity, draws, combosOf };
  if (typeof module !== 'undefined') module.exports = PK.Range;
})();
